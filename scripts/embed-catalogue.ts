/**
 * Writes supabase/migrations/0008_tag_embeddings.sql: gte-small embeddings for every catalogue tag
 * plus same-category model neighbours. Downloads the model on first run.
 *
 *   npx tsx scripts/embed-catalogue.ts
 */
import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { embed } from '../src/lib/matching/embed-local';
import { centreByCategory, computeNeighbors, tagEmbeddingText } from '../src/lib/matching/neighbors';
import type { CatalogueTag } from './catalogue-constants';

const root = path.resolve(__dirname, '..');
const lit = (s: string) => `'${s.replace(/'/g, "''")}'`;
const r6 = (n: number) => Number(n.toFixed(6));

async function main() {
  const tags: CatalogueTag[] = JSON.parse(readFileSync(path.join(root, 'supabase/seed-data/catalogue.json'), 'utf8'));
  const vecs: Float32Array[] = [];
  for (let i = 0; i < tags.length; i += 32) {
    vecs.push(...(await embed(tags.slice(i, i + 32).map(tagEmbeddingText))));
  }
  const rounded = vecs.map((v) => Array.from(v, (x) => Number(x.toFixed(6)))); // plain numbers: float32 would print ~17 digits
  const neighbors = computeNeighbors(centreByCategory(tags.map((t, i) => ({ slug: t.slug, category: t.category, vec: vecs[i] }))));
  neighbors.sort((x, y) => x.a.localeCompare(y.a) || y.sim - x.sim || x.b.localeCompare(y.b));

  const sql = [
    '-- 0008: gte-small tag embeddings and model-derived same-category neighbours.',
    '-- GENERATED by scripts/embed-catalogue.ts from supabase/seed-data/catalogue.json. Do not edit by hand.',
    '-- CONVENTION: taxonomy_tags.embedding = RAW normalised gte-small vectors, used only for query->tag retrieval',
    '-- with its own raw-cosine threshold (calibrated in the tag-search task). tag_neighbors.sim = per-category',
    '-- mean-centred cosine, compared only with neighborMin. The category means are not persisted.',
    '-- Safe to run more than once. Never touches source = \'curated\' neighbour rows.',
    '',
    ...tags.map((t, i) => `update public.taxonomy_tags set embedding = '[${rounded[i].join(',')}]' where slug = ${lit(t.slug)};`),
    '',
    "delete from public.tag_neighbors where source = 'model';",
    'insert into public.tag_neighbors (tag_a, tag_b, sim, source) values',
    neighbors.map((n) => `  (${lit(n.a)}, ${lit(n.b)}, ${r6(n.sim)}, 'model')`).join(',\n'),
    'on conflict (tag_a, tag_b) do nothing;',
    '',
  ].join('\n');
  writeFileSync(path.join(root, 'supabase/migrations/0008_tag_embeddings.sql'), sql);
  console.log(`${tags.length} embeddings, ${neighbors.length} neighbour rows`);
}

main().catch((e) => {
  console.error(e);
  process.exit(1);
});
