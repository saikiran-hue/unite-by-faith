/**
 * Fetches the BSB text of every reference in verse-refs.ts from bible-api.com and writes
 * src/lib/verses/data.ts. The app itself never calls the API.
 *
 *   npx tsx scripts/fetch-verses.ts
 *
 * Responses are cached by query in node_modules/.cache/fetch-verses.json, written after every
 * successful fetch, so a re-run only fetches new or failed references. A full run takes about 14 minutes.
 */
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { cleanVerseText, normalizeRef } from '../src/lib/verses/clean';
import { VERSE_REFS } from './verse-refs';

const DELAY_MS = 2200; // bible-api.com allows 15 requests per 30 s
const RATE_LIMIT_WAIT_MS = 30_000;
const MAX_RATE_LIMIT_RETRIES = 3;
const MAX_LENGTH = 240;

const ROOT = fileURLToPath(new URL('..', import.meta.url));
const CACHE_PATH = path.join(ROOT, 'node_modules/.cache/fetch-verses.json');
const DATA_PATH = path.join(ROOT, 'src/lib/verses/data.ts');
const HEADER = '// Generated by scripts/fetch-verses.ts from bible-api.com (BSB, public domain). Do not edit by hand.';

/** A reference and its text: raw from the API in the cache, normalized and cleaned in data.ts. */
type Fetched = { ref: string; text: string };

const sleep = (ms: number) => new Promise((resolve) => setTimeout(resolve, ms));

/** GETs one query, waiting out HTTP 429 up to 3 times before stopping the whole run. */
async function get(key: string, query: string): Promise<Response> {
  const url = `https://bible-api.com/${encodeURIComponent(query)}?translation=bsb`;
  for (let retry = 0; ; retry++) {
    const res = await fetch(url);
    if (res.status !== 429) return res;
    if (retry === MAX_RATE_LIMIT_RETRIES) {
      throw new Error(`${key} "${query}": still HTTP 429 after ${MAX_RATE_LIMIT_RETRIES} retries; stopping.`);
    }
    console.warn(`${key} "${query}": HTTP 429, waiting 30 s (retry ${retry + 1} of ${MAX_RATE_LIMIT_RETRIES})`);
    await sleep(RATE_LIMIT_WAIT_MS);
  }
}

/** Lists every entry that breaks a rule checked by src/lib/verses/verses.test.ts. */
function ruleBreaks(verses: Record<string, Fetched>): string[] {
  const breaks: string[] = [];
  const keys = VERSE_REFS.map((e) => e.key);
  if (keys.length !== 366) breaks.push(`verse-refs.ts has ${keys.length} entries, not 366`);
  for (let d = new Date(2024, 0, 1); d.getFullYear() === 2024; d.setDate(d.getDate() + 1)) {
    const day = `${String(d.getMonth() + 1).padStart(2, '0')}-${String(d.getDate()).padStart(2, '0')}`;
    const count = keys.filter((k) => k === day).length;
    if (count !== 1) breaks.push(`${day}: ${count} entries`);
  }

  const firstUse = new Map<string, string>();
  for (const [key, { ref, text }] of Object.entries(verses)) {
    const problems: string[] = [];
    const earlier = firstUse.get(ref);
    if (earlier) problems.push(`same reference as ${earlier}`);
    else firstUse.set(ref, key);
    if (text.length === 0 || text.length > MAX_LENGTH) problems.push(`${text.length} characters`);
    if (/\s{2}|\n/.test(text)) problems.push('stray whitespace');
    let depth = 0;
    for (const ch of text) {
      if (ch === '“') depth++;
      if (ch === '”') depth--;
      if (depth < 0) break;
    }
    if (depth !== 0) problems.push('quotes do not nest');
    if (!/^“?[A-Z]/.test(text)) problems.push('starts mid-sentence');
    if (!/[.!?]”?$/.test(text)) problems.push('ends mid-sentence');
    if (problems.length) breaks.push(`${key} ${ref}: ${problems.join(', ')}\n    ${text}`);
  }
  return breaks;
}

async function main() {
  const cache: Record<string, Fetched> = existsSync(CACHE_PATH) ? JSON.parse(readFileSync(CACHE_PATH, 'utf8')) : {};
  mkdirSync(path.dirname(CACHE_PATH), { recursive: true });

  const failures: string[] = [];
  let requested = false;
  for (const { key, ref: query } of VERSE_REFS) {
    if (cache[query]) continue;
    if (requested) await sleep(DELAY_MS);
    requested = true;
    const res = await get(key, query);
    const body: { reference?: string; text?: string } | null = res.ok ? await res.json().catch(() => null) : null;
    if (!body?.reference || !body.text?.trim()) {
      const why = res.ok ? 'no reference or text in the response' : `HTTP ${res.status}`;
      failures.push(`${key} "${query}": ${why}`);
      console.error(`FAILED ${key} "${query}": ${why}`);
      continue;
    }
    cache[query] = { ref: body.reference, text: body.text };
    writeFileSync(CACHE_PATH, JSON.stringify(cache, null, 2));
    console.log(`${key} ${body.reference}`);
  }
  if (failures.length) {
    console.error(`\n${failures.length} entries failed, so data.ts was not written. Re-run to retry them:`);
    console.error(failures.join('\n'));
    process.exit(1);
  }

  const verses: Record<string, Fetched> = {};
  for (const { key, ref: query } of VERSE_REFS) {
    verses[key] = { ref: normalizeRef(cache[query].ref), text: cleanVerseText(cache[query].text) };
  }
  const lines = Object.entries(verses).map(
    ([key, v]) => `  ${JSON.stringify(key)}: { ref: ${JSON.stringify(v.ref)}, text: ${JSON.stringify(v.text)} },`,
  );
  writeFileSync(
    DATA_PATH,
    `${HEADER}\nimport type { Verse } from './index';\n\nexport const VERSES: Record<string, Verse> = {\n${lines.join('\n')}\n};\n`,
  );
  console.log(`\nWrote ${lines.length} verses to src/lib/verses/data.ts`);

  const breaks = ruleBreaks(verses);
  if (breaks.length) {
    console.error(`\n${breaks.length} entries break a data rule; swap their refs in scripts/verse-refs.ts and re-run:`);
    console.error(breaks.join('\n'));
    process.exitCode = 1;
  } else {
    console.log('Every entry passes the data rules.');
  }
}

main().catch((e) => {
  console.error(e);
  process.exit(1);
});
