/**
 * Builds supabase/migrations/0007_catalogue_seed.sql from the reviewable seed data.
 *
 *   GEONAMES_DIR=<dir> npx tsx scripts/import-cities.ts     # once, writes cities.sql
 *   GEONAMES_DIR=<dir> npx tsx scripts/build-catalogue-sql.ts
 */
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { GEONAMES_ATTRIBUTION } from '../src/lib/attribution';
import { CATEGORY_ORDER, SUBGROUPS, TRADITION_FAMILIES, type CatalogueTag, type Tradition } from './catalogue-constants';
import { citiesSqlPath } from './import-cities';

const root = path.resolve(__dirname, '..');
const lit = (s: string) => `'${s.replace(/'/g, "''")}'`;
const arr = (a: string[]) => (a.length ? `array[${a.map(lit).join(', ')}]::text[]` : `'{}'::text[]`);

const tags: CatalogueTag[] = JSON.parse(readFileSync(path.join(root, 'supabase/seed-data/catalogue.json'), 'utf8'));
const traditions: Tradition[] = JSON.parse(readFileSync(path.join(root, 'supabase/seed-data/traditions.json'), 'utf8'));

// Same order as the owner review file: category, then subgroup, then source order.
const ordered = CATEGORY_ORDER.flatMap((c) =>
  (SUBGROUPS[c] as readonly string[]).flatMap((s) => tags.filter((t) => t.category === c && t.subgroup === s)),
);
if (ordered.length !== tags.length) throw new Error('Catalogue has a tag with an unknown category or subgroup');
for (const t of traditions) {
  if (!(TRADITION_FAMILIES as readonly string[]).includes(t.family)) throw new Error(`Unknown family: ${t.family}`);
}

const legacyPairs = tags.flatMap((t) => t.legacySlugs.map((old) => [old, t.slug] as const));

const tagRows = ordered.map(
  (t, i) =>
    `  (${lit(t.slug)}, ${lit(t.label)}, ${lit(t.category)}, ${lit(t.subgroup)}, ${lit(t.description)}, ${arr(t.synonyms)}, ${i + 1})`,
);
const traditionRows = traditions.map((t, i) => `  (${lit(t.id)}, ${lit(t.name)}, ${lit(t.family)}, ${i + 1})`);

const rewriteArray = (table: string, col: string) => `
update public.${table} x
set ${col} = (
  select coalesce(array_agg(s order by first_pos), '{}'::text[])
  from (
    select coalesce(m.new_slug, a.slug) as s, min(a.pos) as first_pos
    from unnest(x.${col}) with ordinality as a(slug, pos)
    left join pg_temp._legacy_map m on m.old_slug = a.slug
    group by 1
  ) deduped
)
where x.${col} && (select coalesce(array_agg(old_slug), '{}'::text[]) from pg_temp._legacy_map);`;

const citiesPath = citiesSqlPath();
if (!existsSync(citiesPath)) {
  throw new Error(`Missing ${citiesPath}. Run: npx tsx scripts/import-cities.ts (set GEONAMES_DIR to choose the folder).`);
}
const citiesSql = readFileSync(citiesPath, 'utf8');

const sql = `-- 0007: curated interest catalogue, church traditions and world cities.
-- GENERATED by scripts/build-catalogue-sql.ts from supabase/seed-data/*.json and GeoNames. Do not edit by hand.
-- ${GEONAMES_ATTRIBUTION}
-- Safe to run more than once. Local verification only until the owner approves it for the hosted project.

-- 1. Traditions -------------------------------------------------------------
insert into public.traditions (id, name, family, sort_order) values
${traditionRows.join(',\n')}
on conflict (id) do update set name = excluded.name, family = excluded.family, sort_order = excluded.sort_order;

-- 2. Tags (icon_name, embedding and popularity are left alone) ---------------
insert into public.taxonomy_tags (slug, label, category, subgroup, description, synonyms, sort_order) values
${tagRows.join(',\n')}
on conflict (slug) do update set
  label = excluded.label,
  category = excluded.category,
  subgroup = excluded.subgroup,
  description = excluded.description,
  synonyms = excluded.synonyms,
  sort_order = excluded.sort_order,
  is_active = true;

-- 3. Legacy slugs -> successors ----------------------------------------------
drop table if exists pg_temp._legacy_map;
create temporary table _legacy_map (old_slug text primary key, new_slug text not null);
insert into pg_temp._legacy_map (old_slug, new_slug) values
${legacyPairs.map(([o, n]) => `  (${lit(o)}, ${lit(n)})`).join(',\n')};

-- user_tags: merged duplicates keep one row (strongest is_priority and level, earliest created_at).
with moved as (
  select ut.user_id, m.new_slug,
         bool_or(ut.is_priority) as is_priority,
         min(ut.created_at) as created_at,
         max(ut.level) as level
  from public.user_tags ut
  join pg_temp._legacy_map m on m.old_slug = ut.tag_slug
  group by ut.user_id, m.new_slug
), removed as (
  delete from public.user_tags where tag_slug in (select old_slug from pg_temp._legacy_map)
)
insert into public.user_tags (user_id, tag_slug, category, is_priority, created_at, level)
select moved.user_id, moved.new_slug, t.category, moved.is_priority, moved.created_at, moved.level
from moved
join public.taxonomy_tags t on t.slug = moved.new_slug
on conflict (user_id, tag_slug) do update set
  is_priority = public.user_tags.is_priority or excluded.is_priority,
  level = greatest(public.user_tags.level, excluded.level),
  category = excluded.category;

-- A tag that kept its slug but moved category (e.g. Group Hangouts) keeps user_tags.category in step.
update public.user_tags ut
set category = t.category
from public.taxonomy_tags t
where t.slug = ut.tag_slug and ut.category <> t.category;
${rewriteArray('pods', 'anchor_tags')}
${rewriteArray('chat_rooms', 'shared_tags')}
${rewriteArray('duo_matches', 'shared_tags')}

drop table pg_temp._legacy_map;

-- 4. Anything not in the catalogue is retired, never deleted (expected: nothing but replaced legacy slugs).
update public.taxonomy_tags
set is_active = false
where is_active and slug <> all (array[${ordered.map((t) => lit(t.slug)).join(', ')}]::text[]);

-- 5. Cities -------------------------------------------------------------------
${citiesSql}`;

const out = path.join(root, 'supabase/migrations/0007_catalogue_seed.sql');
writeFileSync(out, sql);
console.log(`Wrote ${out} (${(sql.length / 1e6).toFixed(2)} MB, ${tags.length} tags, ${traditions.length} traditions, ${legacyPairs.length} legacy rewrites)`);
